export function translateText(value, language = "sr") {
  const text = String(value);
  if (language !== "en") return text;
  const trimmed = text.trim();
  let result = translations.get(trimmed);
  if (result === undefined) {
    const colors = { Crveni:"Red", Plavi:"Blue", Žuti:"Yellow", Zeleni:"Green" };
    const patterns = [
      [/^(\d+(?:\/\d+)?) igrača$/, m => m[1] + " players"],
      [/^Bacio (\d+)$/, m => "Rolled " + m[1]],
      [/^Potez (\d+)$/, m => "Turn " + m[1]],
      [/^Palo je (\d+)$/, m => "Rolled " + m[1]],
      [/^Figura (\d+)$/, m => "Piece " + m[1]],
      [/^Pomeri figuru (\d+)$/, m => "Move piece " + m[1]],
      [/^(Crveni|Plavi|Žuti|Zeleni) figura (\d+)(, dostupna za pomeranje)?$/, m => colors[m[1]] + " piece " + m[2] + (m[3] ? ", available to move" : "")],
      [/^(.+) baca za početak(\.)?$/, m => m[1] + " rolls to start" + (m[2] || "")],
      [/^(.+) je na potezu(\.)?$/, m => m[1] + "'s turn" + (m[2] || "")],
      [/^(.+) je pobedio\/la!$/, m => m[1] + " won!"],
      [/^(.+) počinje partiju\.$/, m => m[1] + " starts the game."],
      [/^(.+) je doveo\/la sve četiri figure u cilj\.$/, m => m[1] + " brought all four pieces home."],
      [/^Još (\d+) pokušaja za šesticu\.$/, m => m[1] + " attempts left to roll a six."],
      [/^Palo je (\d+)\. Još (\d+) pokušaja za šesticu\.$/, m => "Rolled " + m[1] + ". " + m[2] + " attempts left to roll a six."],
      [/^Palo je (\d+)\. Nema mogućeg poteza\.$/, m => "Rolled " + m[1] + ". No legal move."],
      [/^Arena Games · (solo|online) partija$/, m => "Arena Games · " + m[1] + " game"],
      [/^Igraš kao (Crveni|Plavi|Žuti|Zeleni)( · domaćin)?$/, m => "Playing as " + colors[m[1]] + (m[2] ? " · host" : "")],
      [/^Kod sobe: (.+)$/, m => "Room code: " + m[1]],
      [/^(.+): bacanje za početak — (\d+)$/, m => m[1] + ": starting roll — " + m[2]],
      [/^(.+): kockica (\d+)( · bez poteza)?$/, m => m[1] + ": die " + m[2] + (m[3] ? " · no move" : "")],
      [/^(.+): figura (\d+) ide (\d+) polja( · izbacivanje)?$/, m => m[1] + ": piece " + m[2] + " moves " + m[3] + " spaces" + (m[4] ? " · capture" : "")]
    ];
    for (const [regex, format] of patterns) {
      const match = trimmed.match(regex);
      if (match) { result = format(match); break; }
    }
  }
  return result === undefined ? text : text.slice(0, text.indexOf(trimmed)) + result + text.slice(text.indexOf(trimmed) + trimmed.length);
}

export function createDomTranslator(root, initialLanguage = "sr") {
  let language = initialLanguage === "en" ? "en" : "sr";
  const textCache = new WeakMap();
  const attributeCache = new WeakMap();
  const attributes = ["aria-label", "title", "placeholder"];

  function translateNode(node) {
    if (node.parentElement?.closest("[data-user-content], script, style")) return;
    const current = node.nodeValue;
    let record = textCache.get(node);
    if (!record || current !== record.display) record = { source: current, display: current };
    const next = translateText(record.source, language);
    record.display = next;
    textCache.set(node, record);
    if (current !== next) node.nodeValue = next;
  }

  function translateAttributes(element) {
    if (element.closest("[data-user-content], script, style")) return;
    let records = attributeCache.get(element);
    if (!records) { records = new Map(); attributeCache.set(element, records); }
    for (const name of attributes) {
      if (!element.hasAttribute(name)) continue;
      const current = element.getAttribute(name);
      let record = records.get(name);
      if (!record || current !== record.display) record = { source: current, display: current };
      const next = translateText(record.source, language);
      record.display = next;
      records.set(name, record);
      if (current !== next) element.setAttribute(name, next);
    }
  }

  function translate() {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let node = walker.currentNode;
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) translateNode(node);
      else if (node.nodeType === Node.ELEMENT_NODE) translateAttributes(node);
      node = walker.nextNode();
    }
  }

  const observer = new MutationObserver(translate);
  observer.observe(root, { childList: true, characterData: true, attributes: true, subtree: true, attributeFilter: attributes });
  return {
    translate,
    setLanguage(next) { language = next === "en" ? "en" : "sr"; translate(); },
    disconnect() { observer.disconnect(); }
  };
}

